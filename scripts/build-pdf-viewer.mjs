// Inlines pdf.js into src/lib/reader/viewer.html and writes it as a TS string
// module, so the WebView can load it with `source={{ html }}` and no local files.
// Run with: npm run build:viewer
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const lib = read('node_modules/pdfjs-dist/legacy/build/pdf.min.mjs');
const worker = read('node_modules/pdfjs-dist/legacy/build/pdf.worker.min.mjs');
const css = read('node_modules/pdfjs-dist/web/pdf_viewer.css');
const version = JSON.parse(read('node_modules/pdfjs-dist/package.json')).version;

// Only the text layer rules are needed (they end where .annotationLayer starts).
const cssStart = css.indexOf('.textLayer{');
const cssEnd = css.indexOf('.annotationLayer{');
if (cssStart < 0 || cssEnd < cssStart) throw new Error('Could not find .textLayer CSS in pdf_viewer.css');
const textLayerCss = css.slice(cssStart, cssEnd);

// A JS string literal that is safe inside an inline <script>.
const jsString = (s) => JSON.stringify(s).replace(/<\/(script)/gi, '<\\/$1');

const replace = (html, marker, value) => {
  if (!html.includes(marker)) throw new Error(`Marker ${marker} missing from viewer.html`);
  return html.replace(marker, () => value);
};

let html = read('src/lib/reader/viewer.html');
html = replace(html, '/*__TEXT_LAYER_CSS__*/', textLayerCss);
html = replace(html, "/*__PDF_LIB__*/''", jsString(lib));
html = replace(html, "/*__PDF_WORKER__*/''", jsString(worker));

const out =
  '// Generated by scripts/build-pdf-viewer.mjs from src/lib/reader/viewer.html. Do not edit.\n' +
  `// pdf.js ${version}\n` +
  `export const PDF_JS_VERSION = ${JSON.stringify(version)};\n` +
  `export const PDF_VIEWER_HTML = ${JSON.stringify(html)};\n`;
writeFileSync(join(root, 'src/lib/reader/pdf-viewer-html.generated.ts'), out);
console.log(`Wrote pdf-viewer-html.generated.ts (${(out.length / 1e6).toFixed(2)} MB, pdf.js ${version})`);
